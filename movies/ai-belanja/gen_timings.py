# Regenerates ALL picture/sound timing from voice/words.json + voice/voice.wav.
#
# When the new VO arrives: replace voice/voice.wav + voice/words.json, run
#   python3 gen_timings.py
# and every shot boundary / event in story.ts (via timing.ts) and in the audio
# pipeline (via voice/timing.json) updates. Nothing else is hand-timed.
#
# Matching is spaceless + punctuation-free, so whisper variants like
# "chat gpt" vs "chatgpt" or "face id" vs "faceid" still match.
import json
import re
import subprocess
import sys

FPS = 30
HERE = __file__.rsplit("/", 1)[0]
VOICE = HERE + "/voice"
WORDS = VOICE + "/words.json"
WAV = VOICE + "/voice.wav"


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


# key -> (anchor phrase, "start"|"end", occurrence 1-based)
ANCHORS = {
    # --- shot boundaries (end of the anchor word) ---
    "S1_END": ("terus ai yang cari checkout dan bayar", "end", 1),   # hook end
    "S2_END": ("beneran kejadian", "end", 1),                        # "tapi ini beneran kejadian"
    "S3_END": ("belanja buat kamu", "end", 1),                       # beat 2 end
    "S4_END": ("sampai bayar", "end", 1),                            # "masukin keranjang, sampai bayar"
    "S5_END": ("face id", "end", 1),                                 # "pakai sidik jari atau face id"
    "S6_END": ("nomor kartu kamu", "end", 1),                        # beat 4 end
    # --- events (start of the anchor word) ---
    "DOTS_POP": ("belikan rice cooker", "start", 1),                 # dots pops out of the phone
    "WALLET_T": ("chatgpt wallet", "start", 1),                      # wallet materialises
    "COMPARE_T": ("bandingin", "start", 1),                          # dots compares the cookers
    "PICK_T": ("masukin keranjang", "start", 1),                     # chosen cooker drops in the cart
    "TAP_T": ("pencet setuju", "start", 1),                          # finger taps the fingerprint
    "TOKEN_T": ("nomor pengganti", "start", 1),                      # card becomes a token
    "WAIT_T": ("nunggu giliran", "start", 1),                        # clock: Indonesia still waiting
    "CTA_T": ("menurut kamu", "start", 1),                           # closing question
}


def main():
    words = json.load(open(WORDS, encoding="utf-8"))
    flat = ""
    char2word = []  # char index -> word index
    for i, w in enumerate(words):
        nw = norm(w["w"])
        for _ in nw:
            char2word.append(i)
        flat += nw
    dur = float(subprocess.check_output(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "csv=p=0", WAV]).decode().strip())
    out = {}
    for key, (phrase, mode, occ) in ANCHORS.items():
        needle = norm(phrase)
        pos, found, start = -1, 0, 0
        for _ in range(occ):
            pos = flat.find(needle, start)
            if pos < 0:
                break
            found += 1
            start = pos + 1
        if found < occ:
            # fallback: try the last 8 chars of the phrase (last word-ish)
            for cut in (8, 6, 4):
                pos = flat.rfind(needle[-cut:])
                if pos >= 0:
                    print(f"WARN {key}: anchor '{phrase}' not found, fell back to suffix '{needle[-cut:]}'", file=sys.stderr)
                    break
            else:
                print(f"WARN {key}: anchor '{phrase}' NOT FOUND, using 0", file=sys.stderr)
                out[key] = 0.0
                continue
        wi = char2word[min(pos + len(needle) - 1, len(char2word) - 1)] if mode == "end" else char2word[pos]
        out[key] = float(words[wi]["e"] if mode == "end" else words[wi]["s"])
    shots = [
        (1, 0.0, out["S1_END"]),
        (2, out["S1_END"], out["S2_END"]),
        (3, out["S2_END"], out["S3_END"]),
        (4, out["S3_END"], out["S4_END"]),
        (5, out["S4_END"], out["S5_END"]),
        (6, out["S5_END"], out["S6_END"]),
        (7, out["S6_END"], dur),
    ]
    total = int(round(dur * FPS))
    fr = lambda t: int(round(t * FPS))
    ts_lines = [
        "// GENERATED by gen_timings.py from voice/words.json — do not hand-edit.",
        "// Re-run `python3 gen_timings.py` after the VO (and words.json) changes.",
        "export const FPS = 30;",
        f"export const TOTAL = {total}; // {dur:.2f} s",
        "",
    ]
    for key, t in sorted(out.items()):
        ts_lines.append(f"export const {key} = {t:.3f}; // f{fr(t)}")
    ts_lines.append("")
    ts_lines.append("export const SHOT_BOUNDS: [number, number][] = [")
    for _id, a, b in shots:
        ts_lines.append(f"  [{fr(a)}, {fr(b)}], // shot {_id}: {a:.2f}-{b:.2f} s")
    ts_lines.append("];")
    ts_lines.append(f"export const FLASH_AT = {fr(out['S1_END'])}; // white flash after the hook")
    open(HERE + "/remotion/src/videos/ai-belanja/timing.ts", "w", encoding="utf-8").write("\n".join(ts_lines) + "\n")
    payload = {"duration": dur, "total_frames": total, "fps": FPS,
               "events": {k: round(v, 3) for k, v in out.items()},
               "shots": [{"id": i, "a": round(a, 3), "b": round(b, 3)} for i, a, b in shots]}
    json.dump(payload, open(VOICE + "/timing.json", "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    print(f"duration {dur:.2f} s -> TOTAL {total} frames")
    for _id, a, b in shots:
        print(f"  shot {_id}: f{fr(a)}-f{fr(b)} ({a:.2f}-{b:.2f} s)")
    for k, v in sorted(out.items()):
        print(f"  {k}: {v:.2f} s (f{fr(v)})")


if __name__ == "__main__":
    main()
